def main():
    M = int(input("Введите высоту основания M: "))
    N = int(input("Введите высоту крыши N: "))

    # Крыша: N рядов, в ряду i — (2i−1) панелей, сумма = N²
    roof = N * N

    # Основание: M рядов, в каждом ряду (2N−1) панелей
    base = M * (2 * N - 1)

    print(f"Всего панелей: {roof + base}")

if __name__ == "__main__":
    main()
